// The skill map (DOM-free): a skill is a codex entry, placed at the journey chapter that teaches it (chapters/taught.ts),
// learned on the steps its entry links there, practised by the campaign levels built around it (CampaignNode.codex), and
// checked by its codex questions, the linked steps' quizzes and the generated ones (bank.ts) (their review memos: ui/review.ts). Basics adds the two
// ideas that have no codex entry. Tiers group the journey: 0 Basics and the map, 1 chapters 1–10, 2 11–15, 3 16–25,
// 4 the rest (prologue and appendices are optional and in no tier). Nothing here is authored per skill: it cannot drift. The skills are
// computed by learn/pathgen.ts into learn/pathindex.ts (npm run manifest; tests/pathindex.test.ts holds it), so My path loads no chapter.

import { outline } from '../chapters/outline';
import type { ChapterMeta } from '../chapters/meta';
import { numOf } from '../chapters/order';
import type { Tier } from './capstones';
import { PATH_SKILLS } from './pathindex';

export interface Skill {
  /** The codex id, or basics:<name> for Basics' own two. */
  id: string;
  title: string;
  tier: Tier;
  /** The chapter that teaches it, and the steps there that do. */
  chapter: string;
  steps: number[];
  /** Review keys (settings.solved / review memo): the codex's Check yourself and the steps' quizzes. */
  checks: string[];
  /** Step reach challenges (settings.solved keys): building it on the stage. */
  reach: string[];
  /** Campaign levels built around it (not lessons), required ones first. */
  levels: string[];
}

export const TIERS: { tier: Tier; title: string; blurb: string }[] = [
  { tier: 0, title: 'Zero', blurb: 'Voltage, bits, binary, a truth table, a program, and how to read a circuit here' },
  { tier: 1, title: 'Foundations', blurb: 'Transistors, gates, binary arithmetic, adders, latches, registers, memory' },
  { tier: 2, title: 'Builder', blurb: 'A first computer, the ALU, register file, the instruction set, a single-cycle CPU, Python down to gates' },
  { tier: 3, title: 'Architect', blurb: 'Fast adders, pipelines, I/O and traps, multiply and divide, caches, microcode, floating point' },
  { tier: 4, title: 'Master', blurb: 'Out of order, multicore, silicon, the GPU, memory systems, communication and signal processing' },
];

type Placed = Pick<ChapterMeta, 'id' | 'num' | 'prologue' | 'appendix'>;

const optional = (c: Placed) => !!(c.prologue || c.appendix);

/** The tier a journey chapter belongs to; null for the prologue and the appendices. */
export function tierOfChapter(c: Placed): Tier | null {
  if (optional(c)) return null;
  // the communication on-ramp has no number, but it comes late in the book and is not part of the floor
  return c.id === 'message' ? 4 : c.num === 0 ? 0 : c.num <= numOf('memory') ? 1 : c.num <= numOf('python') ? 2 : c.num <= numOf('widths') ? 3 : 4;
}

/** The journey chapters of a tier, in order. */
export const tierChapters = (t: Tier): ChapterMeta[] => outline.filter((c) => tierOfChapter(c) === t);

/** A campaign level as My path needs it (learn/pathindex.ts PATH_LEVELS). */
export interface LevelFact { title: string; kind: string; requires: string[]; optional?: true }

/** A review question as My path counts it: key, chapter ('' for none), generated (1). */
export type ReviewRow = [string, string, 0 | 1];

/** Basics' ideas without a codex entry, checked by its recap's questions. */
export const BASICS: { id: string; title: string; step: number; recap: number }[] = [
  { id: 'basics:loop', title: 'A closed loop', step: 0, recap: 1 },
  { id: 'basics:levels', title: 'Two levels', step: 2, recap: 2 },
];

/** Every skill, in journey order (chapter, then the first step that teaches it): learn/pathindex.ts, generated by pathgen.ts. */
export const skills = (): Skill[] => PATH_SKILLS;

/** The skills a chapter teaches. */
export const skillsOfChapter = (id: string): Skill[] => skills().filter((s) => s.chapter === id);
