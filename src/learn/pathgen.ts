// Builds learn/pathindex.ts and learn/recaps.ts from the live modules (DOM-free; run by scripts/chapter-manifest.ts, compared with the
// checked-in files by tests/pathindex.test.ts). My path and Where are you starting? read those files instead of the chapters, the codex
// and the campaign's nodes, which bring the whole book and the component library: their chunks stay a few files.

import { CODEX } from '../campaign/codex';
import { checkOf, moreOf } from '../campaign/codexmore';
import { NODES } from '../campaign/nodes';
import { chapters } from '../chapters';
import { TAUGHT } from '../chapters/taught';
import { allQuestions } from '../ui/reviewqs';
import { DRILL_REVIEW, REVIEW_BANK } from './bank';
import { stepMinutes } from './minutes';
import { BASICS, tierOfChapter, type LevelFact, type ReviewRow, type Skill } from './skills';

/** Every skill, in journey order (chapter, then the first step that teaches it): what learn/skills.ts skills() returns. */
export function computeSkills(): Skill[] {
  const order = new Map(chapters.map((c, i) => [c.id, i]));
  const out: Skill[] = [];
  for (const b of BASICS) out.push({ id: b.id, title: b.title, tier: 0, chapter: 'basics', steps: [b.step], checks: [`basics:recap:${b.recap}`], reach: [], levels: [] });
  for (const e of CODEX) {
    const chId = TAUGHT[e.id];
    const ch = chId ? chapters.find((c) => c.id === chId) : undefined;
    const tier = ch && tierOfChapter(ch);
    if (!ch || tier === null || tier === undefined) continue;
    const steps = [...new Set((moreOf(e.id)?.chapters ?? []).filter((l) => l.chapter === chId && l.step !== undefined).map((l) => l.step!))].sort((a, b) => a - b);
    const quiz = steps.filter((i) => ch.steps[i]?.challenge?.kind === 'quiz').map((i) => `${chId}:${i}`);
    const reach = steps.filter((i) => ch.steps[i]?.challenge?.kind === 'reach').map((i) => `${chId}:${i}`);
    const lv = NODES.filter((n) => n.kind !== 'lesson' && !n.soon && n.codex?.includes(e.id));
    out.push({
      id: e.id, title: e.title.replace(/\s*\([^)]*\)\s*$/, ''), tier, chapter: chId, steps: steps.length ? steps : [0],
      checks: [...(checkOf(e.id) ?? []).map((_, k) => `codex:${e.id}:${k}`), ...quiz], reach,
      levels: [...lv.filter((n) => !n.optional), ...lv.filter((n) => n.optional)].map((n) => n.id),
    });
  }
  // generated questions (learn/bank.ts): a beat to predict counts for the skills its step teaches, a part to remove for the entries drawing it
  for (const b of REVIEW_BANK) for (const s of out) if (b.kind === 'predict' ? s.chapter === b.chapter && s.steps.includes(b.step) : b.codex.includes(s.id)) s.checks.push(b.key);
  for (const d of DRILL_REVIEW) for (const s of out) if (d.codex.includes(s.id)) s.checks.push(`drill:${d.drill}`);
  const at = (s: Skill) => (order.get(s.chapter) ?? 0) * 1000 + s.steps[0];
  return out.sort((a, b) => at(a) - at(b));
}

export interface PathIndex {
  minutes: Record<string, number[]>;
  skills: Skill[];
  levels: Record<string, LevelFact>;
  review: ReviewRow[];
}

/** What My path needs, from the live modules. Reads every step's body (warm the book first in a test). */
export function pathIndexOf(): PathIndex {
  const skills = computeSkills();
  const levels: Record<string, LevelFact> = {};
  for (const id of [...new Set(skills.flatMap((s) => s.levels))].sort()) {
    const n = NODES.find((x) => x.id === id)!;
    levels[id] = { title: n.title, kind: n.kind, requires: [...n.requires], ...(n.optional ? { optional: true } : {}) };
  }
  return {
    minutes: Object.fromEntries(chapters.map((c) => [c.id, c.steps.map(stepMinutes)])),
    skills,
    levels,
    review: allQuestions().map((q) => [q.key, q.chapter ?? '', q.generated ? 1 : 0]),
  };
}

const HEADER = (what: string) => `// GENERATED by scripts/chapter-manifest.ts (npm run manifest): do not edit. ${what}\n// One line per item so that branches merge; tests/pathindex.test.ts fails when it is stale (run npm run manifest).\n`;
const j = (v: unknown) => JSON.stringify(v);

/** The text of learn/pathindex.ts. */
export function pathIndexSource(x: PathIndex = pathIndexOf()): string {
  return `${HEADER('What My path and Where are you starting? need (learn/pathgen.ts),')}import type { LevelFact, ReviewRow, Skill } from './skills';

/** Minutes per step, by chapter (learn/minutes.ts). */
export const PATH_MINUTES: Record<string, number[]> = {
${Object.entries(x.minutes).map(([k, v]) => `  ${j(k)}: ${j(v)},`).join('\n')}
};

/** Every skill, in journey order (learn/pathgen.ts computeSkills). */
export const PATH_SKILLS: Skill[] = [
${x.skills.map((s) => `  ${j(s)},`).join('\n')}
];

/** The campaign levels the skills name. */
export const PATH_LEVELS: Record<string, LevelFact> = {
${Object.entries(x.levels).map(([k, v]) => `  ${j(k)}: ${j(v)},`).join('\n')}
};

/** Every review question (ui/reviewqs.ts allQuestions, in its order): key, chapter ('' for none), generated. */
export const PATH_REVIEW: ReviewRow[] = [
${x.review.map((r) => `  ${j(r)},`).join('\n')}
];
`;
}

/** The text of learn/recaps.ts: every chapter's recap questions, loaded by a test-out or the placement check. */
export function recapsSource(): string {
  const rows = chapters.filter((c) => c.recap?.check?.length).map((c) => `  ${j(c.id)}: ${j(c.recap!.check)},`);
  return `${HEADER('Every chapter\'s recap questions, for test-out and placement (learn/placement.ts),')}import type { Quiz } from '../chapters/types';

export const RECAPS: Record<string, Quiz[]> = {
${rows.join('\n')}
};
`;
}
