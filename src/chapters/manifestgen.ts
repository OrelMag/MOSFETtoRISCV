// Builds chapters/manifest.ts and chapters/loaders.ts from the chapters (DOM-free; run by scripts/chapter-manifest.ts, compared with
// the checked-in files by tests/chapter-manifest.test.ts). Add what a list needs per chapter or step in meta.ts and here.

import type { ChapterMeta } from './meta';
import type { Chapter } from './types';

export const MANIFEST_HEADER = '// GENERATED by scripts/chapter-manifest.ts (npm run manifest): do not edit. The outline of every chapter (chapters/meta.ts), one line per\n// chapter and per step so that two branches editing different steps merge. tests/chapter-manifest.test.ts fails when it is stale.\n';

/** The outline of a chapter: what meta.ts lists. */
export function metaOf(c: Chapter): ChapterMeta {
  const m: ChapterMeta = { id: c.id, num: c.num, title: c.title, blurb: c.blurb, level: c.level, steps: [] };
  if (c.appendix) m.appendix = c.appendix;
  if (c.prologue) m.prologue = c.prologue;
  if (c.label) m.label = c.label;
  if (c.builds?.length) m.builds = c.builds;
  if (c.recap) m.recap = { checks: c.recap.check?.length ?? 0 };
  m.steps = c.steps.map((s) => ({ title: s.title, ...(s.challenge ? { challenge: s.challenge.kind } : {}), ...(s.scene ? { stage: 'scene' as const } : s.widget ? { stage: 'widget' as const } : {}) }));
  return m;
}

const q = (s: string) => JSON.stringify(s);

/** The text of chapters/manifest.ts. */
export function manifestSource(chs: readonly Chapter[]): string {
  const rows = chs.map((c) => {
    const m = metaOf(c);
    const { steps, ...head } = m;
    const headTxt = Object.entries(head).map(([k, v]) => `${k}: ${JSON.stringify(v)}`).join(', ');
    const stepTxt = steps.map((s) => `    { title: ${q(s.title)}${s.challenge ? `, challenge: ${q(s.challenge)}` : ''}${s.stage ? `, stage: ${q(s.stage)}` : ''} },`).join('\n');
    return `  { ${headTxt}, steps: [\n${stepTxt}\n  ] },`;
  });
  return `${MANIFEST_HEADER}import type { ChapterMeta } from './meta';\n\nexport const MANIFEST: readonly ChapterMeta[] = [\n${rows.join('\n')}\n];\n`;
}

/** Where each chapter's object is exported from: id → [module file without extension, export name]. */
export type Locations = Record<string, [string, string]>;

/** The text of chapters/loaders.ts: one literal import() per chapter, so the bundler gives each its own chunk. */
export function loadersSource(chs: readonly Chapter[], where: Locations): string {
  const rows = chs.map((c) => {
    const w = where[c.id];
    if (!w) throw new Error(`chapter ${c.id} is not exported from any chapters/ch-*.ts module`);
    return `  ${q(c.id)}: () => import('./${w[0]}').then((m) => m.${w[1]}),`;
  });
  return `${MANIFEST_HEADER}import type { Chapter } from './types';\n\n/** A chapter's module, loaded when it is opened (chapters/load.ts). */\nexport const LOADERS: Record<string, () => Promise<Chapter>> = {\n${rows.join('\n')}\n};\n`;
}
